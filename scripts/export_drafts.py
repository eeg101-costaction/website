#!/usr/bin/env python3
"""Copy draft Events, calendar dates and Spotlights into _data/drafts.yml.

An item is live only when its file says `published: true`; _config.yml makes
everything else a draft, and Jekyll leaves drafts out of the site completely.
The drafts page (/drafts/) can therefore not read them from the collections, so
the content-check workflow runs this after every save and commits the result.
The page then shows each draft exactly as it will look once published, for the
writer and the reviewers.

It also writes a small JSON file listing every item (draft or live, ready for
review or not) and the reviewers from _data/site.yml (content_reviewers), which
the workflow uses to open and close "Ready for review" issues.

Usage: python3 scripts/export_drafts.py [--review-json PATH] [--root DIR]
Only rewrites _data/drafts.yml when its content changes.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_event_booking import is_published, load_items  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
COLLECTIONS = {"events": "_events", "dates": "_dates", "spotlights": "_spotlights"}
EDITOR = "https://app.pagescms.org/eeg101-costaction/website/main/collection/{name}/edit/{path}"
SITE = "https://www.eeg101.eu"

# Text Jekyll (Ruby's YAML 1.1 reader) would take for a number although PyYAML
# would write it unquoted: "1,200" is 1200 to Jekyll. Always quote such text.
NUMBER_LIKE = re.compile(r"^[-+]?(\.?[0-9][0-9_,:.]*([eE][-+]?[0-9]+)?|0[xXbBoO][0-9a-fA-F_,]+)$")


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str):
    style = '"' if NUMBER_LIKE.match(value) else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, _str)


def collect(root: Path) -> tuple[dict, list[dict]]:
    drafts: dict[str, list[dict]] = {}
    review: list[dict] = []
    for name, folder in COLLECTIONS.items():
        items, _ = load_items(root / folder)  # problems are reported by the validator
        drafts[name] = []
        for item in items:
            path = f"{folder}/{item['id']}.md"
            edit_url = EDITOR.format(name=name, path=quote(path, safe=""))
            published = is_published(item)
            review.append({
                "key": f"{name}/{item['id']}",
                "collection": name,
                "id": item["id"],
                "title": str(item.get("title") or item["id"]),
                "published": published,
                "ready": item.get("ready_for_review") is True,
                "edit_url": edit_url,
                "preview_url": f"{SITE}/drafts/#{name}-{item['id']}",
                "live_url": f"{SITE}/spotlights/{item['id']}/" if name == "spotlights" else f"{SITE}/{'events/#event-' + item['id'] if name == 'events' else 'calendar/'}",
            })
            if not published:
                entry = {k: v for k, v in item.items() if k != "published"}
                entry["edit_url"] = edit_url
                if name == "spotlights":
                    # Cards link to the preview below them, not to a page that does not exist yet.
                    entry["url"] = f"/drafts/#spotlights-{item['id']}"
                drafts[name].append(entry)
    return drafts, review


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--review-json", type=Path)
    args = parser.parse_args()

    drafts, review = collect(args.root)
    header = ("# Generated by scripts/export_drafts.py after every save in the website editor.\n"
              "# Do not edit: change the item in the editor instead. Shown at /drafts/.\n")
    text = header + yaml.dump(drafts, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=1000)
    target = args.root / "_data" / "drafts.yml"
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8")
        print(f"_data/drafts.yml: {sum(len(v) for v in drafts.values())} draft(s).")
    if args.review_json:
        site = yaml.safe_load((args.root / "_data" / "site.yml").read_text(encoding="utf-8")) or {}
        reviewers = [{"name": str(r.get("name") or ""), "github": str(r.get("github") or "").lstrip("@").strip()}
                     for r in site.get("content_reviewers") or [] if isinstance(r, dict)]
        endpoint = str(site.get("event_booking_endpoint") or "").strip()
        args.review_json.write_text(json.dumps({"reviewers": reviewers, "email_endpoint": endpoint, "items": review},
                                               indent=1, default=str),
                                    encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
